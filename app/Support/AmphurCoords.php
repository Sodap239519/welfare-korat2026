    /**
     * พิกัดศูนย์กลางอำเภอ + กระจายแบบ deterministic (กันหมุดทับกัน)
     * @return array{0: float|null, 1: float|null} [lat, lng]
     */
    public static function withOffset(?string $amphurName, int $seed): array
    {
        $base = self::COORDS[$amphurName] ?? null;
        if (!$base) return [null, null];

        // กระจายในรัศมี ~±0.045° (~5 กม.) รอบศูนย์กลางอำเภอ
        $h = ($seed * 2654435761) & 0x7FFFFFFF;
        $dLat = ((($h % 1000) / 1000) - 0.5) * 0.09;
        $dLng = (((intdiv($h, 1000) % 1000) / 1000) - 0.5) * 0.09;

        return [round($base[0] + $dLat, 6), round($base[1] + $dLng, 6)];
    }
